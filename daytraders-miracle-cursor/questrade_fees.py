    def calculate_commission(self, shares: int, is_etf_buy: bool = False) -> float:
        """Calculate commission for a trade.
        
        Args:
            shares: Number of shares traded
            is_etf_buy: True if buying an ETF (free on Questrade)
        
        Returns:
            Commission in CAD
        """
