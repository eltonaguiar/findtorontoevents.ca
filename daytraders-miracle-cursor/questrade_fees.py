        is_foreign = stock_currency.upper() != self.account_currency
        buy_fx = self.calculate_fx_fee(buy_value, uses_cdr) if is_foreign else 0.0
        sell_fx = self.calculate_fx_fee(sell_value, uses_cdr) if is_foreign else 0.0
