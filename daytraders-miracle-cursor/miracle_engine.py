def fetch_stock_data(symbol: str, period: str = "1y") -> Optional[dict]:
    """Fetch OHLCV data for a symbol using yfinance.

    Returns dict with numpy arrays: opens, highs, lows, closes, volumes
    plus info dict with name, exchange, market cap, etc.
    """
    if yf is None or pd is None:
        return None
    try:
        ticker = yf.Ticker(symbol)
        hist = ticker.history(period=period, auto_adjust=True)
        if hist is None or hist.empty or len(hist) < 5:
            return None

        info = {}
        try:
            fast_info = ticker.fast_info
            info = {
                "name": getattr(fast_info, 'long_name', None) or symbol,
                "exchange": getattr(fast_info, 'exchange', 'UNKNOWN'),
                "market_cap": getattr(fast_info, 'market_cap', None),
                "currency": getattr(fast_info, 'currency', 'USD'),
            }
        except Exception:
            info = {"name": symbol, "exchange": "UNKNOWN", "market_cap": None, "currency": "USD"}

        return {
            "symbol": symbol,
            "opens": hist["Open"].to_numpy(dtype=float),
            "highs": hist["High"].to_numpy(dtype=float),
            "lows": hist["Low"].to_numpy(dtype=float),
            "closes": hist["Close"].to_numpy(dtype=float),
            "volumes": hist["Volume"].to_numpy(dtype=float),
            "dates": hist.index.tolist(),
            "info": info,
        }
    except Exception as e:
        print(f"[FETCH] Error fetching {symbol}: {e}")
        return None


