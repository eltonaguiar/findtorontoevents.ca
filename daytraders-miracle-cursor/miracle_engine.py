def scan_universe(
    universe: list[str] = None,
    strategy: dict = None,
    weights: dict = None,
    db: MiracleCursorDB = None,
    top_n: int = 10,
    min_score: float = 65.0,
) -> list[dict]:
    """Scan a universe of stocks, score them, and return the top picks.

    Args:
        universe: List of ticker symbols. Defaults to FULL_UNIVERSE.
        strategy: Strategy dict from DB.
        weights: Custom weights. Defaults to DEFAULT_WEIGHTS.
        db: Database instance.
        top_n: Max number of picks to return.
        min_score: Minimum composite score to qualify.

    Returns:
        List of scored stock dicts, sorted by score descending.
    """
    if db is None:
        db = MiracleCursorDB()
    if universe is None:
        universe = FULL_UNIVERSE
    if strategy:
        min_score = strategy.get("min_score", min_score)

    print(f"\n{'='*70}")
    print(f"  DayTraders Miracle_CURSOR - Scanning {len(universe)} stocks")
    print(f"  Strategy: {strategy['strategy_name'] if strategy else 'Default'}")
    print(f"  Min Score: {min_score} | Top N: {top_n}")
    print(f"  Time: {datetime.utcnow().isoformat()}Z")
    print(f"{'='*70}\n")

    # Fetch SPY for relative strength
    print("[SCAN] Fetching SPY for relative strength baseline...")
    spy_closes = fetch_spy_closes()

    results = []
    scan_date = datetime.utcnow().strftime("%Y-%m-%d")

    for i, symbol in enumerate(universe):
        print(f"[SCAN] ({i+1}/{len(universe)}) {symbol}...", end=" ", flush=True)

        data = fetch_stock_data(symbol, period="1y")
        if data is None:
            print("SKIP (no data)")
            continue

        indicators = compute_all_indicators(data, spy_closes)
        scored = compute_composite_score(indicators, symbol, db, weights, strategy)

        # Log scan result
        db.insert_scan_result(
            scan_date, symbol,
            strategy["strategy_name"] if strategy else "Default",
            scored["score"],
            scored["score"] >= min_score,
            json.dumps({"rsi": scored["rsi_14"], "vol": scored.get("volume_surge"), "atr": scored["atr_14"]})
        )

        if scored["score"] >= min_score:
            results.append(scored)
            print(f"PASS  score={scored['score']}  rating={scored['rating']}")
        else:
            print(f"FAIL  score={scored['score']}")

    # Sort by score descending
    results.sort(key=lambda x: x["score"], reverse=True)

    # Return top N
    top_picks = results[:top_n]

    print(f"\n{'='*70}")
    print(f"  SCAN COMPLETE: {len(results)} passed filter, returning top {len(top_picks)}")
    print(f"{'='*70}\n")

    return top_picks


