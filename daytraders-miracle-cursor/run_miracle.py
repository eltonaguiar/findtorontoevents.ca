def cmd_fees(args, db):
    """Show Questrade fee comparison (CDR vs non-CDR)."""
    calc = QuestradeFeeCaclulator(account_currency="CAD")
    print("\n  Questrade Fee Comparison: CDR vs Direct US Stock Purchase")
    print("  " + "=" * 65)

    test_cases = [
        ("AAPL", 100, 200.0, 210.0),
        ("NVDA", 10, 800.0, 840.0),
        ("INTC", 200, 50.0, 52.5),
        ("META", 30, 600.0, 630.0),
    ]

    for symbol, shares, entry, exit_p in test_cases:
        cdr = db.get_cdr_for_symbol(symbol)
        no_cdr = calc.calculate_round_trip_cost(shares, entry, exit_p, "USD", uses_cdr=False)
        with_cdr = calc.calculate_round_trip_cost(shares, entry, exit_p, "USD", uses_cdr=True)

        print(f"\n  {symbol} ({shares} shares @ ${entry} -> ${exit_p}):")
        print(f"    Direct US:  Cost ${no_cdr['total_cost']:>8.2f}  |  Net P&L ${no_cdr['net_pnl']:>8.2f}  ({no_cdr['net_return_pct']:+.2f}%)")
        if cdr:
            print(f"    CDR ({cdr['cdr_symbol']}): Cost ${with_cdr['total_cost']:>8.2f}  |  Net P&L ${with_cdr['net_pnl']:>8.2f}  ({with_cdr['net_return_pct']:+.2f}%)")
            print(f"    CDR Savings: ${no_cdr['total_cost'] - with_cdr['total_cost']:.2f}")
        else:
            print(f"    No CDR available for {symbol}")


