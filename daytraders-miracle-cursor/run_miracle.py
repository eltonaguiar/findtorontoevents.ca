def cmd_learn(args, db):
    """Feed a closed signal's outcome to the Oracle."""
    oracle = AdaptiveOracle(db)
    if args.signal_id:
        result = oracle.learn_from_outcome(args.signal_id, args.strategy_id or 7)
        print(json.dumps(result, indent=2, default=str))
    elif args.learn_all:
        # Learn from all closed signals that haven't been processed
        conn = db._connect()
        closed = conn.execute(
            """SELECT signal_id, strategy_id FROM trading_signals_1
               WHERE status = 'closed'
               AND signal_id NOT IN (SELECT signal_id FROM feedback_loop_1)"""
        ).fetchall()
        conn.close()

        if not closed:
            print("  No unprocessed closed signals found.")
            return

        print(f"  Processing {len(closed)} closed signals...")
        for row in closed:
            result = oracle.learn_from_outcome(row["signal_id"], row["strategy_id"])
            print(f"  Learned from signal #{row['signal_id']}: {result.get('outcome', '?')}")
    else:
        print("  Specify --signal-id N or --learn-all")


